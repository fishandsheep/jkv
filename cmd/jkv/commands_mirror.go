package main

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
)

func cmdMirror(ctx context.Context, args []string) error {
	if len(args) == 0 {
		return usageErrorf("用法: jkv mirror <maven|gradle|status> [--apply]")
	}
	apply := false
	for _, arg := range args[1:] {
		switch arg {
		case "--apply":
			apply = true
		default:
			return usageErrorf("mirror 不支持选项 %q", arg)
		}
	}
	home, _ := os.UserHomeDir()
	switch args[0] {
	case "maven":
		path := filepath.Join(home, ".m2", "settings-jkv.xml")
		content := `<?xml version="1.0" encoding="UTF-8"?>
<settings xmlns="http://maven.apache.org/SETTINGS/1.0.0">
  <mirrors><mirror><id>jkv-aliyun</id><name>Aliyun public mirror</name><url>https://maven.aliyun.com/repository/public</url><mirrorOf>*</mirrorOf></mirror></mirrors>
</settings>
`
		if !apply {
			previewConfig("Maven 阿里云公共仓库", path, content)
			return nil
		}
		if err := writeConfig(path, content); err != nil {
			return err
		}
		active := filepath.Join(home, ".m2", "settings.xml")
		if _, err := os.Stat(active); err == nil {
			fmt.Println("已生成:", path)
			fmt.Printf("%s 已存在，拒绝覆盖；使用 mvn -s %s\n", active, path)
			return nil
		}
		if err := copyFile(path, active); err != nil {
			return err
		}
		fmt.Println("已启用 Maven 阿里云公共仓库:", active)
	case "gradle":
		path := filepath.Join(home, ".gradle", "init.d", "jkv-mirrors.gradle")
		content := `// Generated by jkv. Delete this file to disable.
settingsEvaluated { settings ->
  settings.pluginManagement.repositories {
    maven { url 'https://maven.aliyun.com/repository/gradle-plugin/' }
    maven { url 'https://maven.aliyun.com/repository/public/' }
    gradlePluginPortal()
  }
}
allprojects {
  repositories {
    maven { url 'https://maven.aliyun.com/repository/public/' }
    maven { url 'https://maven.aliyun.com/repository/google/' }
    mavenCentral()
  }
}
`
		if !apply {
			previewConfig("Gradle 阿里云依赖镜像", path, content)
			return nil
		}
		if err := writeConfig(path, content); err != nil {
			return err
		}
		fmt.Println("已启用 Gradle 阿里云依赖镜像:", path)
	case "status":
		status := []map[string]any{
			{"tool": "maven", "path": filepath.Join(home, ".m2", "settings-jkv.xml")},
			{"tool": "gradle", "path": filepath.Join(home, ".gradle", "init.d", "jkv-mirrors.gradle")},
		}
		for _, item := range status {
			_, err := os.Stat(item["path"].(string))
			item["configured"] = err == nil
		}
		if optionsFromContext(ctx).JSON {
			return writeJSON(status)
		}
		for _, item := range status {
			if item["configured"].(bool) {
				fmt.Println("存在", item["path"])
			} else {
				fmt.Println("未配置", item["path"])
			}
		}
	default:
		return usageErrorf("不支持镜像配置 %q", args[0])
	}
	return nil
}

// previewConfig shows what --apply would write, without touching the disk.
func previewConfig(name, path, content string) {
	fmt.Println("预览", name, "（未写入；加 --apply 启用）")
	fmt.Println("目标文件:", path)
	fmt.Println("---")
	fmt.Print(content)
	fmt.Println("---")
}

func writeConfig(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if b, err := os.ReadFile(path); err == nil && string(b) != content {
		return stateErrorf("%s 已存在且内容不同，拒绝覆盖", path)
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

func copyFile(src, dst string) error {
	b, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, b, 0o644)
}
